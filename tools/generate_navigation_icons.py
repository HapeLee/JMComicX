"""Generate Android vectors and SVG previews from the navigation SVG sources (stdlib only)."""

from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/navigation-icons"
DRAWABLE = ROOT / "app/src/main/res/drawable"
SVG = "http://www.w3.org/2000/svg"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("", SVG)
ET.register_namespace("android", ANDROID)


def source_path(name):
    return ET.parse(SOURCE / f"{name}.svg").getroot().find(f"{{{SVG}}}path")


for name in ("home-outlined", "profile-filled"):
    path = source_path(name)
    vector = ET.Element("vector", {
        f"{{{ANDROID}}}width": "24dp", f"{{{ANDROID}}}height": "24dp",
        f"{{{ANDROID}}}viewportWidth": "24", f"{{{ANDROID}}}viewportHeight": "24",
    })
    attrs = {
        f"{{{ANDROID}}}pathData": path.attrib["d"],
        f"{{{ANDROID}}}fillColor": "#00000000" if path.get("fill") == "none" else "#FF000000",
    }
    for svg_key, android_key in (
        ("stroke", "strokeColor"), ("stroke-width", "strokeWidth"),
        ("stroke-linecap", "strokeLineCap"), ("stroke-linejoin", "strokeLineJoin"),
    ):
        if svg_key in path.attrib:
            attrs[f"{{{ANDROID}}}{android_key}"] = "#FF000000" if svg_key == "stroke" else path.attrib[svg_key]
    ET.SubElement(vector, "path", attrs)
    ET.indent(vector)
    target = DRAWABLE / f"jmx_nav_{name.replace('-', '_')}.xml"
    target.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tools/generate_navigation_icons.py; MIUIX derivative, Apache-2.0. -->\n'
        + ET.tostring(vector, encoding="unicode") + "\n", encoding="utf8",
    )


def svg_element(parent, tag, **attrs):
    return ET.SubElement(parent, f"{{{SVG}}}{tag}", {k.replace("_", "-"): str(v) for k, v in attrs.items()})


def preview(animated):
    canvas = ET.Element(f"{{{SVG}}}svg", {
        "width": "720", "height": "300", "viewBox": "0 0 720 300",
        "role": "img", "aria-label": "Navigation icons: outlined and filled",
    })
    style = svg_element(canvas, "style")
    style.text = """
      text { font-family: 'Segoe UI', sans-serif; fill: #30343b; text-anchor: middle; }
    """
    if animated:
        style.text += """
          .outline { opacity: 1; animation: outline 3.2s ease-in-out infinite; }
          .fill { opacity: 0; animation: fill 3.2s ease-in-out infinite; }
          @keyframes outline { 0%,25%,100% { opacity: 1; } 45%,75% { opacity: 0; } }
          @keyframes fill { 0%,25%,100% { opacity: 0; } 45%,75% { opacity: 1; } }
          @media (prefers-reduced-motion: reduce) { .outline,.fill { animation: none; } }
        """
    svg_element(canvas, "rect", width=720, height=300, rx=24, fill="#f5f6f8")
    svg_element(canvas, "text", x=360, y=38, font_size=19, font_weight=600).text = (
        "Outlined / Filled — crossfade" if animated else "MIUIX navigation — Outlined / Filled"
    )
    for index, (name, label) in enumerate((("home", "Home"), ("bookshelf", "Bookshelf"), ("profile", "Profile"))):
        center = 132 + index * 228
        if animated:
            group = svg_element(canvas, "g", transform=f"translate({center - 36} 105) scale(3)", color="#292d34")
            for state, css_class in (("outlined", "outline"), ("filled", "fill")):
                layer = svg_element(group, "g", **{"class": css_class})
                layer.append(deepcopy(source_path(f"{name}-{state}")))
        else:
            for y, state in ((65, "outlined"), (155, "filled")):
                group = svg_element(canvas, "g", transform=f"translate({center - 28} {y}) scale(2.333333)", color="#292d34")
                group.append(deepcopy(source_path(f"{name}-{state}")))
        svg_element(canvas, "text", x=center, y=250, font_size=16).text = label
    svg_element(canvas, "text", x=360, y=280, font_size=12).text = (
        "Open in a browser to play. App transitions follow page swipe progress."
        if animated else "Top: unselected    Bottom: selected    |    24 × 24 vector assets"
    )
    ET.indent(canvas)
    filename = "preview-animated.svg" if animated else "preview.svg"
    preview_svg = ET.tostring(canvas, encoding="unicode")
    (SOURCE / filename).write_text(
        "\n".join(line.rstrip() for line in preview_svg.splitlines()) + "\n", encoding="utf8"
    )


preview(animated=False)
preview(animated=True)

# A deterministic comparison of transition progress, renderable without browser animation.
canvas = ET.Element(f"{{{SVG}}}svg", {"width": "720", "height": "330", "viewBox": "0 0 720 330"})
svg_element(canvas, "rect", width=720, height=330, rx=24, fill="#f5f6f8")
style = svg_element(canvas, "style")
style.text = "text { font-family: 'Segoe UI', sans-serif; fill: #30343b; text-anchor: middle; }"
svg_element(canvas, "text", x=360, y=35, font_size=19).text = "Outlined / Filled — simple crossfade"
for column, progress in enumerate((0, 0.25, 0.5, 0.75, 1)):
    center = 92 + column * 134
    svg_element(canvas, "text", x=center, y=70, font_size=14).text = f"{progress:.0%}"
    for row, name in enumerate(("home", "bookshelf", "profile")):
        group = svg_element(canvas, "g", transform=f"translate({center - 24} {88 + row * 74}) scale(2)", color="#292d34")
        for state, opacity in (("outlined", 1 - progress), ("filled", progress)):
            layer = svg_element(group, "g", opacity=opacity)
            layer.append(deepcopy(source_path(f"{name}-{state}")))
ET.indent(canvas)
(SOURCE / "preview-fill-steps.svg").write_text(ET.tostring(canvas, encoding="unicode") + "\n", encoding="utf8")
print("Generated 2 Android vectors and 3 SVG previews.")
